const fs = require('node:fs');
const path = require('node:path');
const { config } = require('../src/config');
const root = path.resolve(__dirname, '..');
const readSource = name => fs.readFileSync(path.join(root, 'src', name + '.js'), 'utf8').split('// Node test exports')[0].trim();
const metadata = `// ==UserScript==
// @name         TwitchAD VAFT MATTEO12SA
// @namespace    https://github.com/MATTEO12SA/twitch-vaft-violentmonkey
// @version      ${config.version}
// @description  Multiple solutions for blocking Twitch ads (vaft)
// @updateURL    https://raw.githubusercontent.com/MATTEO12SA/twitch-vaft-violentmonkey/main/vaft.user.js
// @downloadURL  https://raw.githubusercontent.com/MATTEO12SA/twitch-vaft-violentmonkey/main/vaft.user.js
// @homepageURL  https://github.com/MATTEO12SA/twitch-vaft-violentmonkey
// @supportURL   https://github.com/MATTEO12SA/twitch-vaft-violentmonkey/issues
// @author       https://github.com/cleanlock/VideoAdBlockForTwitch#credits
// @license      MIT
// @match        https://www.twitch.tv/*
// @match        https://twitch.tv/*
// @run-at       document-start
// @inject-into  page
// @grant        none
// ==/UserScript==`;
const output = `${metadata}
// Copyright (c) 2020-present TwitchAdSolutions Contributors. MIT; see LICENSE.
// Generated by npm run build. Edit src/, then rebuild; no remote @require.
(function () {
    'use strict';
    if (window.top !== window.self || window.__VAFT_MATTEO_ACTIVE__) return;
    Object.defineProperty(window, '__VAFT_MATTEO_ACTIVE__', { value: true, configurable: true });
    const config = ${JSON.stringify(config, null, 4)};
${['network', 'hls', 'player', 'worker', 'runtime'].map(readSource).join('\n\n')}
    const runtime = createVaftRuntime({ window, document, setTimeout, clearTimeout, MutationObserver }, config,
        createNetworkTools, createHlsTools, createPlayerController, createWorkerEngine, workerBootstrap);
    runtime.start();
})();
`;
const destination = path.join(root, 'vaft.user.js');
if (process.argv.includes('--check')) {
    if (fs.readFileSync(destination, 'utf8') !== output) {
        console.error('vaft.user.js is stale. Run npm run build and commit the result.');
        process.exitCode = 1;
    }
} else fs.writeFileSync(destination, output);
